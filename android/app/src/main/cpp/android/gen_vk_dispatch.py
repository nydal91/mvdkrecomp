#!/usr/bin/env python3
# Generates vk_dispatch_gen.inc: every Vulkan command of the headers the runtime compiles against (deps/include/vulkan:
# vulkan_core.h, vulkan_android.h), each a function of the same name and signature that calls through a pointer, and
# the table of names to load them by. vk_dispatch.c includes it. Run again when the headers change:
#   python3 app/src/main/cpp/android/gen_vk_dispatch.py
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
INC = os.path.join(HERE, '..', 'deps', 'include', 'vulkan')
HEADERS = ['vulkan_core.h', 'vulkan_android.h']
# commands vk_dispatch.c defines itself (they load the others)
OWN = {'vkGetInstanceProcAddr', 'vkGetDeviceProcAddr', 'vkCreateInstance', 'vkCreateDevice',
       'vkEnumerateInstanceVersion', 'vkEnumerateInstanceExtensionProperties', 'vkEnumerateInstanceLayerProperties'}

proto = re.compile(r'VKAPI_ATTR\s+([\w\s\*]+?)\s+VKAPI_CALL\s+(vk\w+)\s*\(([^;]*?)\)\s*;', re.S)


def arg_names(params):
    params = params.strip()
    if params == 'void' or not params:
        return []
    names = []
    for p in params.split(','):
        p = re.sub(r'\[.*?\]', '', p.strip())  # (arrays: float blendConstants[4])
        names.append(re.findall(r'\w+', p)[-1])
    return names


cmds = []
seen = set()
for h in HEADERS:
    text = open(os.path.join(INC, h)).read()
    for m in proto.finditer(text):
        ret, name, params = ' '.join(m.group(1).split()), m.group(2), ' '.join(m.group(3).split())
        if name in seen:
            continue
        seen.add(name)
        cmds.append((ret, name, params))

out = ['// Generated by gen_vk_dispatch.py from deps/include/vulkan (%s): do not edit.' % ', '.join(HEADERS)]
out.append('#define VKD_COUNT %d' % len(cmds))
out.append('static const char *const vkd_names[VKD_COUNT] = {')
out += ['    "%s",' % n for _, n, _ in cmds]
out.append('};')
out.append('static PFN_vkVoidFunction vkd_fn[VKD_COUNT];')
for i, (ret, name, params) in enumerate(cmds):
    if name in OWN:
        out.append('#define VKD_%s %d' % (name, i))
        continue
    args = ', '.join(arg_names(params))
    call = '((PFN_%s)vkd_fn[%d])(%s)' % (name, i, args)
    body = ('return ' + call) if ret != 'void' else call
    out.append('VKAPI_ATTR %s VKAPI_CALL %s(%s) { %s; }' % (ret, name, params, body))
open(os.path.join(HERE, 'vk_dispatch_gen.inc'), 'w').write('\n'.join(out) + '\n')
print('%d commands' % len(cmds))
